import os

import pandas as pd
import requests
import streamlit as st

API_BASE_URL = os.environ.get("TELEMETRY_API", "http://127.0.0.1:8000")

st.set_page_config(page_title="Bus Stop Cooling Monitor", page_icon="🚌", layout="wide")
st.title("Bus Stop Cooling Monitor")
st.error("SIMULATED DATA — readings are generated by a software simulator, not a physical ESP32.")
st.caption(
    "Prototype dashboard · local FastAPI telemetry service · crowd level means "
    "people waiting at the stop, not passengers onboard the bus."
)


@st.fragment(run_every="5s")
def render_dashboard() -> None:
    try:
        response = requests.get(f"{API_BASE_URL}/telemetry?limit=500", timeout=3)
        response.raise_for_status()
        items = response.json()["items"]
    except requests.RequestException as error:
        st.warning(
            f"Cannot reach the telemetry API at {API_BASE_URL}. "
            "Start the FastAPI server, then refresh this page."
        )
        st.caption(str(error))
        return

    if not items:
        st.info("No readings received yet. Start simulator.py to populate the dashboard.")
        return

    data = pd.DataFrame(items)
    data["timestamp"] = pd.to_datetime(data["timestamp"], utc=True, errors="coerce")
    data = data.dropna(subset=["timestamp"]).sort_values("timestamp")
    latest = data.groupby("device_id", as_index=False).tail(1).sort_values("device_id")

    st.subheader("Current stop status")
    for start in range(0, len(latest), 3):
        columns = st.columns(3)
        for column, (_, reading) in zip(columns, latest.iloc[start : start + 3].iterrows()):
            fault = reading["fault_code"]
            state = "FAULT" if pd.notna(fault) and fault else (
                "Cooling" if reading["cooler_on"] else "Standby"
            )
            with column:
                st.markdown(f"#### {reading['device_id']}")
                st.metric("Air temperature", f"{reading['temperature_c']:.1f} °C")
                st.metric("Relative humidity", f"{reading['humidity_pct']:.1f}%")
                st.metric("Water level", f"{reading['water_level_pct']:.1f}%")
                st.metric("Waiting-area crowd", reading["crowd_level"])
                st.caption(f"Crowd data source: {reading['crowd_source']}")
                st.metric("Power", f"{reading['power_w']:.1f} W")
                st.write(f"**State:** {state}")
                if pd.notna(fault) and fault:
                    st.warning(f"Simulated fault: {fault}")
                st.caption(f"Last update: {reading['timestamp'].strftime('%H:%M:%S UTC')}")

    st.subheader("Recent readings")
    device_ids = sorted(data["device_id"].unique().tolist())
    selected = st.selectbox("Select a stop", device_ids)
    history = data[data["device_id"] == selected].tail(120).set_index("timestamp")
    chart_col1, chart_col2 = st.columns(2)
    with chart_col1:
        st.markdown("**Temperature (°C)**")
        st.line_chart(history[["temperature_c"]], height=230)
    with chart_col2:
        st.markdown("**Humidity (%)**")
        st.line_chart(history[["humidity_pct"]], height=230)

    st.markdown("**Water and power**")
    st.line_chart(history[["water_level_pct", "power_w"]], height=220)

    shown = data.sort_values("timestamp", ascending=False).head(20).copy()
    shown["timestamp"] = shown["timestamp"].dt.strftime("%Y-%m-%d %H:%M:%S UTC")
    shown["cooler_on"] = shown["cooler_on"].map({True: "On", False: "Off"})
    st.dataframe(
        shown[
            [
                "timestamp",
                "device_id",
                "temperature_c",
                "humidity_pct",
                "water_level_pct",
                "power_w",
                "cooler_on",
                "crowd_level",
                "crowd_source",
                "fault_code",
            ]
        ],
        width="stretch",
        hide_index=True,
    )


render_dashboard()
